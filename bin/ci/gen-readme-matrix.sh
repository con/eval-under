# Regenerate the README's CI matrix table from .github/matrix.yaml.
#
# Replaces the old gen-dispatchers.sh, which also had to emit 20
# near-identical workflow files -- one per cell, purely so that each cell
# had a workflow-level badge URL. .github/workflows/test.yaml is now a
# single matrix over the same data, and the per-cell badges are SVGs we
# render ourselves onto the site branch (bin/ci/publish-status.sh).
#
# Each badge links to that cell's anchor on the report page, which is
# regenerated every run with a deep link to the cell's actual job log.
# GitHub has no stable URL for "the latest job of this matrix cell", so
# that indirection is what makes a badge clickable at all.
#
# The badge images are served from raw.githubusercontent rather than from
# Pages, so the grid renders even before Pages has been enabled on the
# repo; only the links need Pages.
#
# usage:
#   bin/ci/gen-readme-matrix.sh            # rewrite the README table
#   bin/ci/gen-readme-matrix.sh --check    # exit 1 if it is stale
#
# env:
#   EVAL_UNDER_SITE_BRANCH   branch holding the site   (gh-pages)

set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
# matrix.sh is a sourced library, resolved at runtime relative to $here.
# shellcheck source=bin/ci/matrix.sh disable=SC1091
. "$here/matrix.sh"

root="$EVAL_UNDER_ROOT"
README="$root/README.md"
BRANCH="${EVAL_UNDER_SITE_BRANCH:-gh-pages}"
BEGIN_MARK='<!-- BEGIN CI MATRIX (generated by bin/ci/gen-readme-matrix.sh) -->'
END_MARK='<!-- END CI MATRIX -->'

CHECK=0
[ "${1:-}" = "--check" ] && CHECK=1

grep -qF "$BEGIN_MARK" "$README" || {
    echo "ERROR: $README has no '$BEGIN_MARK' marker" >&2
    exit 1
}

owner="${EVAL_UNDER_REPO_SLUG%%/*}"
name="${EVAL_UNDER_REPO_SLUG#*/}"

badge_url() {
    echo "https://raw.githubusercontent.com/$EVAL_UNDER_REPO_SLUG/$BRANCH/badges/$1.svg"
}

# Anchor on the report page, which carries the deep link to this cell's
# most recent job log.
cell_url() {
    echo "https://$owner.github.io/$name/#$1"
}

table_md() {
    printf '| Backend |'
    for target in "${EVAL_UNDER_TARGETS[@]}"; do
        printf ' %s |' "$(target_label "$target")"
    done
    printf '\n| --- |'
    for _ in "${EVAL_UNDER_TARGETS[@]}"; do printf ' --- |'; done
    printf '\n'

    for cell in "${EVAL_UNDER_BACKENDS[@]}"; do
        IFS='|' read -r backend version label _runs_on <<< "$cell"
        printf '| %s |' "$label"
        for target in "${EVAL_UNDER_TARGETS[@]}"; do
            slug="$(cell_slug "$backend" "$version" "$target")"
            printf ' [![%s / %s](%s)](%s) |' \
                "$label" "$(target_label "$target")" \
                "$(badge_url "$slug")" "$(cell_url "$slug")"
        done
        printf '\n'
    done
}

new_readme="$(mktemp)"
trap 'rm -f "$new_readme"' EXIT

awk -v begin="$BEGIN_MARK" -v end="$END_MARK" -v table="$(table_md)" '
    $0 == begin { print; print table; skip = 1; next }
    $0 == end   { skip = 0 }
    !skip       { print }
' "$README" > "$new_readme"

if [ "$CHECK" = 1 ]; then
    if diff -q "$README" "$new_readme" >/dev/null 2>&1; then
        echo "up to date: README CI matrix"
        exit 0
    fi
    echo "stale: README.md CI matrix (run bin/ci/gen-readme-matrix.sh)" >&2
    exit 1
fi

cp "$new_readme" "$README"
echo "refreshed the README CI matrix ($((${#EVAL_UNDER_BACKENDS[@]} * ${#EVAL_UNDER_TARGETS[@]})) cells)"
