# Regenerate the README's CI matrix table from .github/matrix.yaml.
#
# Replaces the old gen-dispatchers.sh, which also had to emit 20
# near-identical workflow files -- one per cell, purely so that each
# cell had a workflow-level badge URL. .github/workflows/test.yaml is
# now a single matrix over the same data, and the per-cell badges are
# SVGs we render ourselves onto the `badges` branch
# (bin/ci/publish-badges.sh). So this only has a table to write.
#
# usage:
#   bin/ci/gen-readme-matrix.sh            # rewrite the README table
#   bin/ci/gen-readme-matrix.sh --check    # exit 1 if it is stale
#
# env:
#   EVAL_UNDER_BADGE_BRANCH   branch holding the SVGs   (badges)

set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
# matrix.sh is a sourced library, resolved at runtime relative to $here.
# shellcheck source=bin/ci/matrix.sh disable=SC1091
. "$here/matrix.sh"

root="$EVAL_UNDER_ROOT"
README="$root/README.md"
BRANCH="${EVAL_UNDER_BADGE_BRANCH:-badges}"
BEGIN_MARK='<!-- BEGIN CI MATRIX (generated by bin/ci/gen-readme-matrix.sh) -->'
END_MARK='<!-- END CI MATRIX -->'

CHECK=0
[ "${1:-}" = "--check" ] && CHECK=1

grep -qF "$BEGIN_MARK" "$README" || {
    echo "ERROR: $README has no '$BEGIN_MARK' marker" >&2
    exit 1
}

# The badge SVG lives on the badges branch; clicking it should land on
# the run that produced it, so link to the workflow's run list.
runs_url="https://github.com/$EVAL_UNDER_REPO_SLUG/actions/workflows/test.yaml"
badge_url() {
    echo "https://raw.githubusercontent.com/$EVAL_UNDER_REPO_SLUG/$BRANCH/$1.svg"
}

table_md() {
    printf '| Backend |'
    for target in "${EVAL_UNDER_TARGETS[@]}"; do
        printf ' %s |' "$(target_label "$target")"
    done
    printf '\n| --- |'
    for _ in "${EVAL_UNDER_TARGETS[@]}"; do printf ' --- |'; done
    printf '\n'

    for cell in "${EVAL_UNDER_BACKENDS[@]}"; do
        IFS='|' read -r backend version label <<< "$cell"
        printf '| %s |' "$label"
        for target in "${EVAL_UNDER_TARGETS[@]}"; do
            slug="$(cell_slug "$backend" "$version" "$target")"
            printf ' [![%s / %s](%s)](%s) |' \
                "$label" "$(target_label "$target")" "$(badge_url "$slug")" "$runs_url"
        done
        printf '\n'
    done
}

new_readme="$(mktemp)"
trap 'rm -f "$new_readme"' EXIT

awk -v begin="$BEGIN_MARK" -v end="$END_MARK" -v table="$(table_md)" '
    $0 == begin { print; print table; skip = 1; next }
    $0 == end   { skip = 0 }
    !skip       { print }
' "$README" > "$new_readme"

if [ "$CHECK" = 1 ]; then
    if diff -q "$README" "$new_readme" >/dev/null 2>&1; then
        echo "up to date: README CI matrix"
        exit 0
    fi
    echo "stale: README.md CI matrix (run bin/ci/gen-readme-matrix.sh)" >&2
    exit 1
fi

cp "$new_readme" "$README"
echo "refreshed the README CI matrix ($((${#EVAL_UNDER_BACKENDS[@]} * ${#EVAL_UNDER_TARGETS[@]})) cells)"
