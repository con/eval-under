# Generated with Claude Code
#
# Maintenance helper (NOT a runner-side step): regenerate the per-cell
# dispatcher workflows and the README CI matrix from bin/ci/matrix.sh.
#
# GitHub exposes one badge per *workflow file*, not per matrix cell, so a
# backends x targets grid in the README needs one thin dispatcher file
# per cell. Hand-maintaining 20 near-identical YAML files is how they
# drift; generating them is how they don't.
#
# usage:
#   bin/ci/gen-dispatchers.sh            # write workflows + README table
#   bin/ci/gen-dispatchers.sh --check    # exit 1 if anything is stale
#
# Run it after editing EVAL_UNDER_BACKENDS / EVAL_UNDER_TARGETS in
# bin/ci/matrix.sh, and commit the result.

set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/../.." && pwd)"
# matrix.sh is a sourced library, resolved at runtime relative to $here.
# shellcheck source=bin/ci/matrix.sh disable=SC1091
. "$here/matrix.sh"

WF_DIR="$root/.github/workflows"
README="$root/README.md"
BEGIN_MARK='<!-- BEGIN CI MATRIX (generated by bin/ci/gen-dispatchers.sh) -->'
END_MARK='<!-- END CI MATRIX -->'

CHECK=0
case "${1:-}" in
    --check) CHECK=1 ;;
    "") ;;
    *) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac

# One trap for every scratch path we create below.
scratch=()
cleanup() { [ "${#scratch[@]}" -eq 0 ] || rm -rf "${scratch[@]}"; }
trap cleanup EXIT

outdir="$WF_DIR"
if [ "$CHECK" = 1 ]; then
    outdir="$(mktemp -d)"
    scratch+=("$outdir")
fi

grep -qF "$BEGIN_MARK" "$README" || {
    echo "ERROR: $README has no '$BEGIN_MARK' marker" >&2
    exit 1
}

badge_url() {
    local file="$1"
    echo "https://github.com/$EVAL_UNDER_REPO_SLUG/actions/workflows/$file"
}

emit_dispatcher() {
    local backend="$1" version="$2" label="$3" target="$4" file="$5"
    local slug fixtures=""
    slug="$(backend_slug "$backend" "$version")"

    # BeeGFS is the only backend with checked-in fixtures worth watching.
    if [ "$backend" = "beegfs" ]; then
        fixtures='      - "fixtures/beegfs/**"
'
    fi

    cat > "$outdir/$file" <<EOF
name: $label / $(target_label "$target")

# GENERATED FILE -- edit bin/ci/matrix.sh and re-run
# bin/ci/gen-dispatchers.sh instead of editing this by hand.
#
# Thin dispatcher so this matrix cell ($slug x $target) gets a distinct
# README badge. All work is delegated to _test-under.yaml (reusable).

on:
  push:
    branches: [main, master]
    paths:
      - "bin/**"
$fixtures      - "provision/**"
      - ".github/workflows/_test-under.yaml"
      - ".github/workflows/$file"
  pull_request:
    paths:
      - "bin/**"
$fixtures      - "provision/**"
      - ".github/workflows/_test-under.yaml"
      - ".github/workflows/$file"
  workflow_dispatch:
  schedule:
    - cron: "$(target_cron_minute "$target") 5 * * 1"  # Mon 05:$(printf '%02d' "$(target_cron_minute "$target")") UTC

concurrency:
  group: $slug-$target-\${{ github.ref }}
  cancel-in-progress: true

jobs:
  call:
    uses: ./.github/workflows/_test-under.yaml
    with:
      backend: "$backend"
      backend-version: "$version"
      target: "$target"
    permissions:
      contents: read
      actions: read
EOF
}

# --- workflows -------------------------------------------------------

declare -a generated=()
for cell in "${EVAL_UNDER_BACKENDS[@]}"; do
    IFS='|' read -r backend version label <<< "$cell"
    slug="$(backend_slug "$backend" "$version")"
    for target in "${EVAL_UNDER_TARGETS[@]}"; do
        file="test-$slug-$target.yaml"
        emit_dispatcher "$backend" "$version" "$label" "$target" "$file"
        generated+=("$file")
    done
done

# --- README table ----------------------------------------------------

table_md() {
    local cell backend version label target file
    printf '| Backend |'
    for target in "${EVAL_UNDER_TARGETS[@]}"; do
        printf ' %s |' "$(target_label "$target")"
    done
    printf '\n| --- |'
    for _ in "${EVAL_UNDER_TARGETS[@]}"; do
        printf ' --- |'
    done
    printf '\n'

    for cell in "${EVAL_UNDER_BACKENDS[@]}"; do
        IFS='|' read -r backend version label <<< "$cell"
        printf '| %s |' "$label"
        for target in "${EVAL_UNDER_TARGETS[@]}"; do
            file="test-$(backend_slug "$backend" "$version")-$target.yaml"
            printf ' [![%s](%s/badge.svg)](%s) |' \
                "$label / $target" "$(badge_url "$file")" "$(badge_url "$file")"
        done
        printf '\n'
    done
}

new_readme="$(mktemp)"
scratch+=("$new_readme")
awk -v begin="$BEGIN_MARK" -v end="$END_MARK" -v table="$(table_md)" '
    $0 == begin { print; print table; skip = 1; next }
    $0 == end   { skip = 0 }
    !skip       { print }
' "$README" > "$new_readme"

# --- report / write --------------------------------------------------

if [ "$CHECK" = 1 ]; then
    rc=0
    for file in "${generated[@]}"; do
        if ! diff -q "$WF_DIR/$file" "$outdir/$file" >/dev/null 2>&1; then
            echo "stale: .github/workflows/$file" >&2
            rc=1
        fi
    done
    # Any dispatcher that is no longer part of the matrix.
    for existing in "$WF_DIR"/test-*.yaml; do
        base="$(basename "$existing")"
        # shellcheck disable=SC2076  # literal match is intended
        if [[ ! " ${generated[*]} " =~ " $base " ]]; then
            echo "orphan: .github/workflows/$base" >&2
            rc=1
        fi
    done
    if ! diff -q "$README" "$new_readme" >/dev/null 2>&1; then
        echo "stale: README.md CI matrix" >&2
        rc=1
    fi
    [ "$rc" = 0 ] && echo "up to date: ${#generated[@]} dispatchers + README matrix"
    exit "$rc"
fi

cp "$new_readme" "$README"
echo "wrote ${#generated[@]} dispatchers into .github/workflows/ and refreshed the README matrix"
printf '  %s\n' "${generated[@]}"
