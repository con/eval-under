# check

# Only `# key: value`, so a test id starting with "#" still reads as a row.
HEADER = re.compile(r"^# (?P<k>[a-z][a-z-]*): ?(?P<v>.*)$")


def read_results(path: Path) -> tuple[dict[str, str], list[tuple[str, str]]]:
    """(header, [(id, outcome)]) from collect-results.py's results.tsv."""
    if not path.is_file():
        return {"complete": "no", "reason": f"no {path.name} (results never collected)"}, []
    header: dict[str, str] = {}
    rows = []
    for line in path.read_text().splitlines():
        m = HEADER.match(line)
        if m:
            header[m.group("k")] = m.group("v").strip()
            continue
        if not line.strip():
            continue
        tid, _, rest = line.partition("\t")
        outcome = rest.partition("\t")[0]
        if outcome not in OUTCOMES:
            header.update(complete="no", reason=f"bad outcome {outcome!r} for {tid!r}")
            continue
        rows.append((tid, outcome))
    return header, rows


def classify(issues: list[Issue], bslug: str, target: str,
             rc: int | None, header: dict, rows: list[tuple[str, str]]) -> dict:
    mine = [i for i in issues if i.applies(bslug, target)]
    counts = dict.fromkeys(OUTCOMES + ("known_fail", "new_fail"), 0)
    per = {i.id: {"fail": 0, "pass": 0, "passed_exact": []} for i in mine}
    new = []
    for tid, outcome in rows:
        counts[outcome] += 1
        hits = [i for i in mine if i.matches(tid)]
        for i in hits:
            s = per[i.id]
            if outcome == "fail":
                s["fail"] += 1
            elif outcome in ("pass", "todo-pass"):
                s["pass"] += 1
                # A literal id passing means that line of the issue can go;
                # a glob passing somewhere says nothing.
                if tid in i.patterns:
                    s["passed_exact"].append(tid)
        if outcome == "fail":
            if hits:
                counts["known_fail"] += 1
            else:
                counts["new_fail"] += 1
                new.append(tid)

    complete = header.get("complete") == "yes"
    reason = "" if complete else header.get("reason", "")
    if rc is None:
        complete, reason = False, "the suite never ran (no suite.rc)"
    elif rc in TIMEOUT_RCS:
        complete, reason = False, f"the suite timed out (exit {rc})"
    elif complete and (rc != 0) != (counts["fail"] > 0):
        # What catches a parser that silently drops failures.
        complete = False
        reason = (f"suite exited {rc} but {counts['fail']} failure(s) were parsed "
                  f"-- the results parser and the suite disagree")

    issues_out = {}
    for i in mine:
        s = per[i.id]
        if s["fail"]:
            status = "reproduced"
        elif not complete:
            status = "unknown"
        elif s["pass"]:
            status = "not-reproduced"
        else:
            status = "stale"
        issues_out[i.id] = {"status": status, "fail": s["fail"], "pass": s["pass"],
                            "coarse": i.coarse,
                            "passed_exact": s["passed_exact"][:MAX_LISTED]}

    if not complete:
        state = "incomplete"
    elif counts["new_fail"]:
        state = "failing-new"
    elif counts["fail"]:
        state = "failing-known"
    else:
        state = "passing"
    return {
        "state": state,
        "conclusion": "success" if state in OK_STATES else "failure",
        "reason": reason,
        "suite_rc": rc,
        "counts": counts,
        "new_failures": new[:MAX_LISTED],
        "issues": issues_out,
    }


def gh(cmd: str, msg: str, title: str) -> None:
    """A GitHub workflow command; harmless plain text anywhere else."""
    msg = msg.replace("%", "%25").replace("\r", "%0D").replace("\n", "%0A")
    print(f"::{cmd} title={title}::{msg}")


def annotate(slug: str, v: dict) -> None:
    if v["state"] == "incomplete":
        gh("error", f"{slug}: {v['reason']}", "incomplete run")
    for t in v["new_failures"][:MAX_ANNOTATIONS]:
        gh("error", f"{slug}: {t} failed and no known issue covers it", "new failure")
    more = v["counts"]["new_fail"] - MAX_ANNOTATIONS
    if more > 0:
        gh("error", f"{slug}: ... and {more} more; see results.tsv", "new failure")
    for iid, e in v["issues"].items():
        if e["status"] == "not-reproduced":
            gh("notice", f"{slug}: '{iid}' did not reproduce -- fixed?",
               "known issue not reproduced")
        elif e["status"] == "stale":
            gh("warning", f"{slug}: '{iid}' matched no test that ran", "stale known issue")
        if e["passed_exact"]:
            gh("notice", f"{slug}: '{iid}' lists tests that now pass: "
               + ", ".join(e["passed_exact"][:MAX_ANNOTATIONS]), "known issue partly fixed")


def summarize(label: str, v: dict) -> str:
    c = v["counts"]
    lines = [f"### {label}: {v['state']}", ""]
    if v["reason"]:
        lines += [f"Incomplete: {v['reason']}", ""]
    lines += [f"pass {c['pass']} · fail {c['fail']} (known {c['known_fail']}, "
              f"new {c['new_fail']}) · skip {c['skip']} · TODO {c['todo']}/{c['todo-pass']} "
              f"(failed/passed)", ""]
    if v["new_failures"]:
        lines += ["New failures:", ""] + [f"- `{t}`" for t in v["new_failures"]] + [""]
    if v["issues"]:
        lines += ["| Known issue | Status | Failed | Passed |", "| --- | --- | --- | --- |"]
        lines += [f"| `{iid}`{' (whole cell)' if e['coarse'] else ''} | {e['status']} "
                  f"| {e['fail']} | {e['pass']} |" for iid, e in v["issues"].items()]
        lines.append("")
    return "\n".join(lines) + "\n"


def cmd_check(a) -> int:
    _, issues = load_valid()
    bslug = backend_slug(a.backend, a.version)
    slug = f"{bslug}-{a.target}"
    cell = matrix_cells(load_matrix()).get(slug, {"label": slug})
    out = Path(a.cell_dir)
    rc_file = out / "suite.rc"
    rc = int(rc_file.read_text()) if rc_file.is_file() else None
    header, rows = read_results(out / "results.tsv")
    v = classify(issues, bslug, a.target, rc, header, rows)
    v.update(cell=slug, backend_slug=bslug, target=a.target)
    out.mkdir(parents=True, exist_ok=True)
    (out / "verdict.json").write_text(json.dumps(v, indent=2, sort_keys=True) + "\n")

    annotate(slug, v)
    summary = summarize(cell["label"], v)
    print(summary)
    if os.environ.get("GITHUB_STEP_SUMMARY"):
        with open(os.environ["GITHUB_STEP_SUMMARY"], "a") as fh:
            fh.write(summary)
    print(f"I: {slug}: state={v['state']} conclusion={v['conclusion']}")
    return 0 if v["conclusion"] == "success" else 1


