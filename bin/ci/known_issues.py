# Judge CI cells against evals/known-issues.yaml. Each cell gets two
# verdicts:
#   state        what the status page shows -- the truth about the
#                filesystem; a cell whose failures are all known is still
#                failing ("failing-known")
#   conclusion   what the job reports -- success unless there is a new
#                failure or the run is incomplete
#
# Also the one home of the matrix naming rules (backend slug, cell label),
# imported by update-status.py and render-report.py -- hence the
# underscore in the name.
#
# env:
#   EVAL_UNDER_MATRIX_FILE         (default: evals/matrix.yaml)
#   EVAL_UNDER_KNOWN_ISSUES_FILE   (default: evals/known-issues.yaml)

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from dataclasses import dataclass, field
from fnmatch import fnmatchcase
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
MATRIX_FILE = Path(os.environ.get("EVAL_UNDER_MATRIX_FILE", ROOT / "evals/matrix.yaml"))
ISSUES_FILE = Path(os.environ.get("EVAL_UNDER_KNOWN_ISSUES_FILE",
                                  ROOT / "evals/known-issues.yaml"))
GOTCHAS_FILE = ROOT / "GOTCHAS.md"
GOTCHAS_BEGIN = "<!-- BEGIN KNOWN ISSUES (generated by bin/ci/known_issues.py gotchas) -->"
GOTCHAS_END = "<!-- END KNOWN ISSUES -->"

OUTCOMES = ("pass", "fail", "skip", "todo", "todo-pass")
STATES = ("passing", "failing-known", "failing-new", "incomplete")
OK_STATES = ("passing", "failing-known")     # states whose job succeeds
TIMEOUT_RCS = (124, 137)                     # timeout(1), and its KILL
MAX_LISTED = 50         # ids per list in verdict.json; results.tsv has all
MAX_ANNOTATIONS = 10    # ::error lines per cell


# --------------------------------------------------------------------------
# the matrix

def backend_slug(backend: str, version: str) -> str:
    # Keep in sync with backend_slug() in bin/ci/matrix.sh.
    return backend if version == "n/a" else f"{backend}-{version}"


def load_matrix(path: Path = MATRIX_FILE) -> dict:
    with path.open() as fh:
        return yaml.safe_load(fh)


def matrix_cells(m: dict) -> dict[str, dict]:
    """slug -> cell metadata, in matrix (row, column) order."""
    cells = {}
    for b in m["backends"]:
        bslug = backend_slug(b["backend"], b["version"])
        for t in m["targets"]:
            cells[f"{bslug}-{t['name']}"] = {
                "backend": b["backend"],
                "version": b["version"],
                "backend_slug": bslug,
                "backend_label": b["label"],
                "target": t["name"],
                "target_label": t["label"],
                "label": f"{b['label']} / {t['label']}",
            }
    return cells


