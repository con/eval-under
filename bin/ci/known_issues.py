# draft

def cmd_draft(a) -> int:
    """Issue stubs for new failures: the bootstrap and triage aid.

    One stub per cell; merging stubs across cells (and giving them a real
    root cause) is deliberately left to a human.
    """
    stubs = []
    for p in a.verdicts:
        v = json.loads(Path(p).read_text())
        if not v.get("new_failures"):
            continue
        cell, bslug, target = v["cell"], v["backend_slug"], v["target"]
        more = v["counts"]["new_fail"] - len(v["new_failures"])
        stubs.append({
            "id": f"{cell}-todo",
            "title": "TODO: root cause",
            "backends": [bslug],
            "targets": [target],
            "expect": "fail",
            "tests": v["new_failures"]
                     + ([f"TODO: {more} more, see results.tsv"] if more > 0 else []),
            "tags": [],
            "links": ["TODO"],
        })
    if stubs:
        print(yaml.safe_dump(stubs, sort_keys=False, width=100))
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(prog="known_issues.py")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("validate")
    p.add_argument("--gotchas", action="store_true",
                   help="also fail if GOTCHAS.md's generated section is stale")
    p.set_defaults(func=cmd_validate)
    p = sub.add_parser("check")
    p.add_argument("backend")
    p.add_argument("version")
    p.add_argument("target")
    p.add_argument("cell_dir")
    p.set_defaults(func=cmd_check)
    p = sub.add_parser("gotchas")
    p.add_argument("--check", action="store_true")
    p.set_defaults(func=cmd_gotchas)
    p = sub.add_parser("draft")
    p.add_argument("verdicts", nargs="+")
    p.set_defaults(func=cmd_draft)
    a = ap.parse_args()
    return a.func(a)


if __name__ == "__main__":
    raise SystemExit(main())
