# GOTCHAS.md generation

def md_link(link: str) -> str:
    """A `links:` entry as Markdown, relative to GOTCHAS.md itself."""
    if "://" in link:
        return f"<{link}>"
    if link.startswith("GOTCHAS.md#"):
        link = link[len("GOTCHAS.md"):]
    return f"[{link}]({link})"


def render_gotchas(d: dict, m: dict) -> str:
    out = [GOTCHAS_BEGIN, "",
           "Generated from [`.github/known-issues.yaml`](.github/known-issues.yaml);",
           "edit that file, then run `bin/ci/known_issues.py gotchas`.", "",
           "| Tag | Meaning |", "| --- | --- |"]
    out += [f"| `{t}` | {desc} |" for t, desc in d["tags"].items()]
    out.append("")
    for i in d["issues"]:
        out.append(f'<a id="{i["id"]}"></a>')
        out.append(f"### `{i['id']}`: {i['title']}")
        out.append("")
        cells = cells_of(i, m)
        meta = [f"**Cells:** {', '.join(f'`{c}`' for c in cells)}"]
        meta.append(f"**Expect:** {i['expect']}"
                    + (" -- whole cell, not yet narrowed to named tests" if is_coarse(i) else ""))
        if i["tags"]:
            meta.append("**Tags:** " + ", ".join(f"`{t}`" for t in i["tags"]))
        if i.get("fixed-in"):
            meta.append(f"**Fixed in:** {i['fixed-in']}")
        out.append(" \\\n".join(meta))
        out.append("")
        if not is_coarse(i):
            out.append("Tests: " + ", ".join(f"`{t}`" for t in i["tests"]))
            out.append("")
        if i.get("notes"):
            out.append(i["notes"].rstrip())
            out.append("")
        out.append("See: " + ", ".join(md_link(l) for l in i["links"]))
        out.append("")
    out.append(GOTCHAS_END)
    return "\n".join(out)


def splice_gotchas(text: str, block: str) -> str:
    b, e = text.find(GOTCHAS_BEGIN), text.find(GOTCHAS_END)
    if b < 0 or e < b:
        raise SystemExit(f"{GOTCHAS_FILE.name}: generated-section markers not found")
    return text[:b] + block + text[e + len(GOTCHAS_END):]


def cmd_gotchas(a) -> int:
    d, m = load(), load_matrix()
    text = GOTCHAS_FILE.read_text()
    new = splice_gotchas(text, render_gotchas(d, m))
    if a.check:
        if new != text:
            print(f"E: {GOTCHAS_FILE.name} is out of date with known-issues.yaml; "
                  f"run bin/ci/known_issues.py gotchas", file=sys.stderr)
            return 1
        return 0
    if new != text:
        GOTCHAS_FILE.write_text(new)
        print(f"I: updated {GOTCHAS_FILE.name}")
    return 0


def cmd_validate(a) -> int:
    errs = validate(load(), load_matrix())
    for e in errs:
        print(f"E: {ISSUES_FILE.name}: {e}", file=sys.stderr)
    if errs:
        return 1
    print(f"I: {ISSUES_FILE.name} is valid")
    return cmd_gotchas(argparse.Namespace(check=True)) if a.gotchas else 0


