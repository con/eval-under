# `<file>#107-108,118-120`: prove's "Failed tests:" syntax, pasteable as is.
RANGES = re.compile(r"^(?P<pre>.*#)(?P<r>\d+(?:-\d+)?(?:\s*,\s*\d+(?:-\d+)?)+|\d+-\d+)$")


def expand(patterns: list[str]) -> list[str]:
    out = []
    for p in patterns:
        m = RANGES.match(p)
        if not m:
            out.append(p)
            continue
        for part in re.split(r"\s*,\s*", m.group("r")):
            a, _, b = part.partition("-")
            lo, hi = int(a), int(b or a)
            if hi < lo:
                raise ValueError(f"reversed range {part!r} in {p!r}")
            out += [f"{m.group('pre')}{n}" for n in range(lo, hi + 1)]
    return out


@dataclass
class Issue:
    id: str
    title: str
    backends: list[str]
    targets: list[str]
    tests: list[str]            # as written, ranges unexpanded
    tags: list[str] = field(default_factory=list)
    links: list[str] = field(default_factory=list)
    notes: str = ""
    patterns: list[str] = field(init=False)

    def __post_init__(self):
        self.patterns = expand(self.tests)

    @property
    def coarse(self) -> bool:
        """Covers the whole cell rather than named tests."""
        return "*" in self.tests

    def applies(self, bslug: str, target: str) -> bool:
        return (any(t in ("*", target) for t in self.targets)
                and any(fnmatchcase(bslug, p) for p in self.backends))

    def matches(self, tid: str) -> bool:
        return any(fnmatchcase(tid, p) for p in self.patterns)


def load(path: Path = ISSUES_FILE) -> dict:
    """The raw YAML; validate() it before parse()."""
    with path.open() as fh:
        return yaml.safe_load(fh) or {}


def str_list(v) -> list[str] | None:
    """v if it is a non-empty list of non-empty strings, else None."""
    ok = isinstance(v, list) and v and all(isinstance(x, str) and x for x in v)
    return v if ok else None


def validate(raw: dict, m: dict) -> list[str]:
    """Every problem, as messages; empty means valid.

    Strict because a typo'd backend or target would silently make an
    issue match nothing.
    """
    errs = []
    vocab = raw.get("tags") or {}
    if not isinstance(vocab, dict):
        return ["tags: must be a mapping of tag -> description"]
    cells = matrix_cells(m).values()
    backends = sorted({c["backend_slug"] for c in cells})
    targets = sorted({c["target"] for c in cells})
    fields = {f for f, d in Issue.__dataclass_fields__.items() if d.init}
    seen = set()
    for n, issue in enumerate(raw.get("issues") or []):
        iid = issue.get("id")
        where = f"issue {iid}" if iid else f"issues[{n}]"
        if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", str(iid)):
            errs.append(f"{where}: id must be lowercase [a-z0-9-]")
        if iid in seen:
            errs.append(f"{where}: duplicate id")
        seen.add(iid)
        errs += [f"{where}: unknown field {k!r}" for k in sorted(set(issue) - fields)]
        if not isinstance(issue.get("title"), str) or not issue["title"]:
            errs.append(f"{where}: title is required")
        lists = {}
        for f in ("backends", "targets", "tests", "tags", "links"):
            if f not in issue and f in ("tags", "links"):
                continue
            lists[f] = str_list(issue.get(f))
            if lists[f] is None:
                errs.append(f"{where}: {f} must be a non-empty list of strings")
        # Left over from `known_issues.py draft`.
        values = [issue.get("title")] + [x for v in lists.values() if v for x in v]
        for v in values:
            if isinstance(v, str) and v.startswith("TODO"):
                errs.append(f"{where}: placeholder {v!r} left in")
        for pat in lists.get("backends") or []:
            if not any(fnmatchcase(b, pat) for b in backends):
                errs.append(f"{where}: backend pattern {pat!r} matches none of "
                            f"{', '.join(backends)}")
        for t in lists.get("targets") or []:
            if t != "*" and t not in targets:
                errs.append(f"{where}: unknown target {t!r} ({', '.join(targets)})")
        for tag in lists.get("tags") or []:
            if tag not in vocab:
                errs.append(f"{where}: tag {tag!r} is not declared under tags:")
        try:
            expand(lists.get("tests") or [])
        except ValueError as e:
            errs.append(f"{where}: tests: {e}")
    return errs


def parse(raw: dict) -> list[Issue]:
    return [Issue(**i) for i in raw.get("issues") or []]


def load_valid() -> tuple[dict, list[Issue]]:
    """(raw, issues), exiting with the messages if the file is invalid."""
    raw = load()
    errs = validate(raw, load_matrix())
    if errs:
        sys.exit("\n".join(f"E: {ISSUES_FILE.name}: {e}" for e in errs))
    return raw, parse(raw)


