# GOTCHAS.md

def md_link(link: str) -> str:
    if "://" in link:
        return f"<{link}>"
    link = link.removeprefix("GOTCHAS.md")     # same-file anchors
    return f"[{link}]({link})"


def render_gotchas(raw: dict, issues: list[Issue], m: dict) -> str:
    cells = matrix_cells(m)
    out = [GOTCHAS_BEGIN, "",
           "Generated from [`evals/known-issues.yaml`](evals/known-issues.yaml) "
           "by `bin/ci/known_issues.py gotchas`.", "",
           "| Tag | Meaning |", "| --- | --- |"]
    out += [f"| `{t}` | {desc} |" for t, desc in raw["tags"].items()]
    for i in issues:
        mine = [s for s, c in cells.items() if i.applies(c["backend_slug"], c["target"])]
        meta = ["**Cells:** " + ", ".join(f"`{s}`" for s in mine)]
        if i.tags:
            meta.append("**Tags:** " + ", ".join(f"`{t}`" for t in i.tags))
        meta.append("**Tests:** " + ("all (whole cell, not yet narrowed down)" if i.coarse
                                     else ", ".join(f"`{t}`" for t in i.tests)))
        out += ["", f'<a id="{i.id}"></a>', f"### `{i.id}`: {i.title}", "",
                " \\\n".join(meta), ""]
        if i.notes:
            out += [i.notes.rstrip(), ""]
        out.append("See: " + ", ".join(md_link(link) for link in i.links))
    out += ["", GOTCHAS_END]
    return "\n".join(out)


def gotchas_text() -> tuple[str, str]:
    """(current GOTCHAS.md, what it should be)."""
    raw, issues = load_valid()
    text = GOTCHAS_FILE.read_text()
    b, e = text.find(GOTCHAS_BEGIN), text.find(GOTCHAS_END)
    if b < 0 or e < b:
        sys.exit(f"E: {GOTCHAS_FILE.name}: generated-section markers not found")
    block = render_gotchas(raw, issues, load_matrix())
    return text, text[:b] + block + text[e + len(GOTCHAS_END):]


def cmd_gotchas(a) -> int:
    old, new = gotchas_text()
    if new != old:
        GOTCHAS_FILE.write_text(new)
        print(f"I: updated {GOTCHAS_FILE.name}")
    return 0


def cmd_validate(a) -> int:
    load_valid()
    print(f"I: {ISSUES_FILE.name} is valid")
    if a.gotchas:
        old, new = gotchas_text()
        if new != old:
            print(f"E: {GOTCHAS_FILE.name} is stale; run bin/ci/known_issues.py gotchas",
                  file=sys.stderr)
            return 1
    return 0


# --------------------------------------------------------------------------
# draft

def cmd_draft(a) -> int:
    stubs = []
    for p in a.verdicts:
        v = json.loads(Path(p).read_text())
        if not v["new_failures"]:
            continue
        more = v["counts"]["new_fail"] - len(v["new_failures"])
        stubs.append({
            "id": re.sub(r"[^a-z0-9-]+", "-", f"{v['cell']}-todo".lower()),
            "title": "TODO: root cause",
            "backends": [v["backend_slug"]],
            "targets": [v["target"]],
            "tests": v["new_failures"] + ([f"TODO: {more} more in results.tsv"] if more > 0 else []),
            "links": ["TODO"],
        })
    if stubs:
        print(yaml.safe_dump(stubs, sort_keys=False, width=100))
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(prog="known_issues.py")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("validate", help="check the YAML against the matrix")
    p.add_argument("--gotchas", action="store_true",
                   help="also fail if GOTCHAS.md's generated section is stale")
    p.set_defaults(func=cmd_validate)
    p = sub.add_parser("check", help="judge one cell; writes <cell-dir>/verdict.json")
    for arg in ("backend", "version", "target", "cell_dir"):
        p.add_argument(arg)
    p.set_defaults(func=cmd_check)
    p = sub.add_parser("gotchas", help="regenerate GOTCHAS.md's Known issues section")
    p.set_defaults(func=cmd_gotchas)
    p = sub.add_parser("draft", help="print issue stubs for new failures in verdict files")
    p.add_argument("verdicts", nargs="+")
    p.set_defaults(func=cmd_draft)
    a = ap.parse_args()
    return a.func(a)


if __name__ == "__main__":
    raise SystemExit(main())
