def read_results(path: Path) -> tuple[dict[str, str], list[tuple[str, str, str]]]:
    """(header, rows). A missing file reads as an incomplete, empty result."""
    header: dict[str, str] = {}
    rows: list[tuple[str, str, str]] = []
    if not path.is_file():
        return {"complete": "no", "reason": f"no {path.name} (results were never collected)"}, rows
    for line in path.read_text().splitlines():
        if not line.strip():
            continue
        if line.startswith("#"):
            k, _, v = line[1:].partition(":")
            header[k.strip()] = v.strip()
            continue
        parts = line.split("\t")
        tid, outcome = parts[0], parts[1] if len(parts) > 1 else ""
        detail = parts[2] if len(parts) > 2 else ""
        if outcome not in OUTCOMES:
            header["complete"] = "no"
            header["reason"] = f"bad outcome {outcome!r} for {tid!r} in {path.name}"
            continue
        rows.append((tid, outcome, detail))
    return header, rows


def version_tuple(v: str) -> tuple[int, ...]:
    return tuple(int(x) for x in re.findall(r"\d+", v))


def classify(issues: list[dict], bslug: str, target: str,
             rc: int | None, header: dict, rows: list) -> dict:
    """The core of `check`, kept pure so it is easy to exercise locally."""
    mine = [i for i in issues if applies(i, bslug, target)]

    def matching(tid: str) -> list[dict]:
        return [i for i in mine if any(fnmatchcase(tid, p) for p in i["_tests"])]

    counts = {k: 0 for k in ("pass", "fail", "skip", "todo", "todo-pass",
                             "known_fail", "flaky_fail", "new_fail")}
    new, per_issue = [], {i["id"]: {"fail": 0, "pass": 0, "failed": [], "passed_exact": []}
                          for i in mine}
    for tid, outcome, _ in rows:
        counts[outcome] += 1
        hits = matching(tid)
        for i in hits:
            s = per_issue[i["id"]]
            if outcome == "fail":
                s["fail"] += 1
                if len(s["failed"]) < MAX_LISTED:
                    s["failed"].append(tid)
            elif outcome in ("pass", "todo-pass"):
                s["pass"] += 1
                # A literal id that now passes is worth naming: that line
                # of the issue can probably go. A glob passing somewhere
                # is expected and says nothing.
                if tid in i["_tests"]:
                    s["passed_exact"].append(tid)
        if outcome != "fail":
            continue
        if any(i["expect"] == "fail" for i in hits):
            counts["known_fail"] += 1
        elif hits:
            counts["flaky_fail"] += 1
        else:
            counts["new_fail"] += 1
            new.append(tid)

    complete = header.get("complete") == "yes"
    reason = header.get("reason", "") if not complete else ""
    if rc is None:
        complete, reason = False, "the suite never ran (no suite.rc)"
    elif rc in (124, 137):
        complete, reason = False, f"the suite timed out (exit {rc})"
    elif complete and (rc != 0) != (counts["fail"] > 0):
        # The suite's own exit code and our parse must agree. This is what
        # catches parser drift after a ref bump or an output-format change:
        # without it, a parser that silently drops failures would read as
        # green.
        complete = False
        reason = (f"suite exited {rc} but {counts['fail']} failure(s) were parsed "
                  f"-- the results parser and the suite disagree")

    tool_version = header.get("version", "")
    issues_out = {}
    for i in mine:
        s = per_issue[i["id"]]
        matched = s["fail"] + s["pass"]
        if not complete and s["fail"] == 0:
            status = "unknown"
        elif s["fail"]:
            status = "reproduced"
        elif matched:
            status = "not-reproduced"
        else:
            status = "stale"
        entry = {"status": status, "expect": i["expect"], "fail": s["fail"],
                 "pass": s["pass"], "coarse": is_coarse(i)}
        if s["failed"]:
            entry["failed"] = s["failed"]
        if s["passed_exact"]:
            entry["passed_exact"] = s["passed_exact"][:MAX_LISTED]
        fixed = i.get("fixed-in")
        if fixed and status == "reproduced" and tool_version:
            tool, want = fixed.split(" ", 1)
            have = tool_version.split(" ", 1)
            if (len(have) == 2 and have[0] == tool
                    and version_tuple(have[1]) >= version_tuple(want)):
                entry["fixed_in_but_reproduced"] = f"{fixed} (running {tool_version})"
        issues_out[i["id"]] = entry

    if not complete:
        state = "incomplete"
    elif counts["new_fail"]:
        state = "failing-new"
    elif counts["fail"]:
        state = "failing-known"
    else:
        state = "passing"
    return {
        "state": state,
        "conclusion": "success" if state in ("passing", "failing-known") else "failure",
        "complete": complete,
        "reason": reason,
        "suite_rc": rc,
        "version": tool_version,
        "counts": counts,
        "new_failures": new[:MAX_LISTED],
        "issues": issues_out,
    }


def gh(cmd: str, msg: str, title: str = "") -> None:
    """A GitHub workflow command; harmless plain text anywhere else."""
    msg = msg.replace("%", "%25").replace("\r", "%0D").replace("\n", "%0A")
    t = f" title={title}" if title else ""
    print(f"::{cmd}{t}::{msg}")


def summarize(label: str, v: dict) -> str:
    c = v["counts"]
    lines = [f"### {label}: {v['state']}", ""]
    if v["reason"]:
        lines += [f"**Incomplete:** {v['reason']}", ""]
    lines += [f"pass {c['pass']} · fail {c['fail']} (known {c['known_fail']}, "
              f"flaky {c['flaky_fail']}, **new {c['new_fail']}**) · skip {c['skip']}"
              + (f" · TODO {c['todo']}/{c['todo-pass']} (failed/passed)"
                 if c["todo"] or c["todo-pass"] else ""), ""]
    if v["new_failures"]:
        lines += ["New failures (not covered by any known issue):", ""]
        lines += [f"- `{t}`" for t in v["new_failures"]] + [""]
    if v["issues"]:
        lines += ["| Known issue | Status | Failed | Passed |", "| --- | --- | --- | --- |"]
        for iid, e in v["issues"].items():
            note = " (whole cell)" if e["coarse"] else ""
            lines.append(f"| `{iid}`{note} | {e['status']} | {e['fail']} | {e['pass']} |")
        lines.append("")
    return "\n".join(lines) + "\n"


def cmd_check(a) -> int:
    m = load_matrix()
    d = load()
    errs = validate(d, m)
    if errs:
        for e in errs:
            gh("error", e, "known-issues.yaml")
        return 1
    bslug = backend_slug(a.backend, a.version)
    slug = f"{bslug}-{a.target}"
    cell = Path(a.cell_dir)
    rc_file = cell / "suite.rc"
    rc = int(rc_file.read_text().strip()) if rc_file.is_file() else None
    header, rows = read_results(cell / "results.tsv")
    v = classify(d["issues"], bslug, a.target, rc, header, rows)
    v.update(cell=slug, backend_slug=bslug, target=a.target)
    cell.mkdir(parents=True, exist_ok=True)
    (cell / "verdict.json").write_text(json.dumps(v, indent=2, sort_keys=True) + "\n")

    label = next((f"{b['label']} / {t['label']}" for b in m["backends"] for t in m["targets"]
                  if backend_slug(b["backend"], b["version"]) == bslug
                  and t["name"] == a.target), slug)
    if not v["complete"]:
        gh("error", f"{slug}: {v['reason']}", "incomplete run")
    for t in v["new_failures"][:10]:
        gh("error", f"{slug}: {t} failed and no known issue covers it", "new failure")
    if v["counts"]["new_fail"] > 10:
        gh("error", f"{slug}: ... and {v['counts']['new_fail'] - 10} more new failure(s); "
           f"see results.tsv in the logs artifact", "new failure")
    for iid, e in v["issues"].items():
        if e["expect"] != "fail":
            continue
        if e["status"] == "not-reproduced":
            gh("notice", f"{slug}: known issue '{iid}' did not reproduce "
               f"({e['pass']} matching test(s) passed, none failed) -- fixed?", "known issue not reproduced")
        elif e["status"] == "stale":
            gh("warning", f"{slug}: known issue '{iid}' matched no test that ran "
               f"-- renamed test or stale pattern?", "stale known issue")
        if e.get("passed_exact"):
            gh("notice", f"{slug}: '{iid}' lists test(s) that now pass: "
               + ", ".join(e["passed_exact"][:10]), "known issue partly fixed")
        if e.get("fixed_in_but_reproduced"):
            gh("warning", f"{slug}: '{iid}' still reproduces although marked fixed-in "
               f"{e['fixed_in_but_reproduced']}", "fixed-in but reproduced")

    summary = summarize(label, v)
    print(summary)
    if os.environ.get("GITHUB_STEP_SUMMARY"):
        with open(os.environ["GITHUB_STEP_SUMMARY"], "a") as fh:
            fh.write(summary)
    print(f"I: {slug}: state={v['state']} conclusion={v['conclusion']}")
    return 0 if v["conclusion"] == "success" else 1


