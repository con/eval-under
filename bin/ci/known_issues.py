# Known issues: the single source of truth for "this cell is red, and we
# know why". Reads .github/known-issues.yaml and
#
#   validate   checks it against .github/matrix.yaml (and, with
#              --gotchas, that GOTCHAS.md's generated section is current)
#   check      classifies one cell's per-test results against it and sets
#              the job's verdict: known failures keep the job green, new
#              failures and incomplete runs turn it red
#   gotchas    regenerates the "Known issues" section of GOTCHAS.md
#   draft      prints issue stubs for the new failures in verdict files,
#              to paste into the YAML and then annotate by hand
#
# Deliberately two verdicts per cell, not one:
#
#   conclusion   what the *job* reports: success unless something changed
#                that we did not already know about (a new failure, or a
#                run that did not complete).
#   state        what the *report* shows: the truth about the filesystem.
#                A cell whose failures are all known is still "failing".
#
# Importable (render-report.py and update-status.py use load()/cell
# helpers), hence the underscore in the name.
#
# usage:
#   bin/ci/known_issues.py validate [--gotchas]
#   bin/ci/known_issues.py check <backend> <version> <target> <cell-dir>
#   bin/ci/known_issues.py gotchas [--check]
#   bin/ci/known_issues.py draft <verdict.json>...
#
# <cell-dir> is what run-under.sh and collect-results.py wrote:
#   suite.rc      exit code of the wrapped suite (absent: never ran)
#   results.tsv   <test-id> TAB <outcome> [TAB <detail>], with `# key: value`
#                 header lines (complete, reason, version)
# check writes <cell-dir>/verdict.json, appends a Markdown summary to
# $GITHUB_STEP_SUMMARY when set, and emits ::error/::warning/::notice
# workflow commands.
#
# env:
#   EVAL_UNDER_MATRIX_FILE         (default: .github/matrix.yaml)
#   EVAL_UNDER_KNOWN_ISSUES_FILE   (default: .github/known-issues.yaml)

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from fnmatch import fnmatchcase
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
MATRIX_FILE = Path(os.environ.get("EVAL_UNDER_MATRIX_FILE", ROOT / ".github/matrix.yaml"))
ISSUES_FILE = Path(os.environ.get("EVAL_UNDER_KNOWN_ISSUES_FILE",
                                  ROOT / ".github/known-issues.yaml"))
GOTCHAS_FILE = ROOT / "GOTCHAS.md"

EXPECT = ("fail", "flaky")
OUTCOMES = ("pass", "fail", "skip", "todo", "todo-pass")
# How many ids to carry per list in verdict.json / annotations. The full
# list is always in results.tsv, uploaded with the cell's logs.
MAX_LISTED = 50

GOTCHAS_BEGIN = "<!-- BEGIN KNOWN ISSUES (generated by bin/ci/known_issues.py gotchas) -->"
GOTCHAS_END = "<!-- END KNOWN ISSUES -->"


# --------------------------------------------------------------------------
# loading and validation

def backend_slug(backend: str, version: str) -> str:
    # Mirror of backend_slug() in bin/ci/matrix.sh.
    return backend if version == "n/a" else f"{backend}-{version}"


def load_matrix(path: Path = MATRIX_FILE) -> dict:
    with path.open() as fh:
        return yaml.safe_load(fh)


def matrix_axes(m: dict) -> tuple[list[str], list[str]]:
    """(backend slugs, target names), in matrix order."""
    return ([backend_slug(b["backend"], b["version"]) for b in m["backends"]],
            [t["name"] for t in m["targets"]])


# `<file>#107-108,118-120`: prove's own "Failed tests:" syntax, so a
# summary line can be pasted straight in. Expanded once, at load time.
RANGES = re.compile(r"^(?P<pre>.*#)(?P<r>\d+(?:-\d+)?(?:\s*,\s*\d+(?:-\d+)?)+|\d+-\d+)$")


def expand(patterns: list[str]) -> list[str]:
    out = []
    for p in patterns:
        m = RANGES.match(p) if isinstance(p, str) else None
        if not m:
            out.append(p)
            continue
        for part in re.split(r"\s*,\s*", m.group("r")):
            a, _, b = part.partition("-")
            out += [f"{m.group('pre')}{n}" for n in range(int(a), int(b or a) + 1)]
    return out


def load(path: Path = ISSUES_FILE) -> dict:
    with path.open() as fh:
        d = yaml.safe_load(fh) or {}
    d.setdefault("tags", {})
    d.setdefault("issues", [])
    for issue in d["issues"]:
        issue.setdefault("expect", "fail")
        issue.setdefault("tags", [])
        issue.setdefault("links", [])
        issue["_tests"] = expand(issue.get("tests") or [])
    return d


def validate(d: dict, m: dict) -> list[str]:
    """Every problem found, as human-readable strings. Empty means valid.

    Strict on purpose: a typo'd tag, backend or target would otherwise
    silently make an issue match nothing, and the cell it was meant to
    cover would go red for a reason nobody can see.
    """
    errs = []
    backends, targets = matrix_axes(m)
    vocab = d.get("tags") or {}
    if not isinstance(vocab, dict):
        return ["tags: must be a mapping of tag -> description"]
    seen = set()
    allowed = {"id", "title", "backends", "targets", "expect", "tests",
               "tags", "fixed-in", "links", "notes"}
    for n, issue in enumerate(d["issues"]):
        where = f"issues[{n}]"
        iid = issue.get("id")
        if not iid or not re.fullmatch(r"[a-z0-9][a-z0-9-]*", str(iid)):
            errs.append(f"{where}: id must be lowercase [a-z0-9-], got {iid!r}")
        else:
            where = f"issue {iid}"
            if iid in seen:
                errs.append(f"{where}: duplicate id")
            seen.add(iid)
        for k in sorted(k for k in set(issue) - allowed if not k.startswith("_")):
            errs.append(f"{where}: unknown field {k!r}")
        if not issue.get("title"):
            errs.append(f"{where}: title is required")
        for field in ("backends", "targets", "tests", "links"):
            v = issue.get(field)
            if not isinstance(v, list) or not v or not all(isinstance(x, str) and x for x in v):
                errs.append(f"{where}: {field} must be a non-empty list of strings")
        for pat in issue.get("backends") or []:
            if isinstance(pat, str) and not any(fnmatchcase(b, pat) for b in backends):
                errs.append(f"{where}: backend pattern {pat!r} matches no backend "
                            f"in the matrix ({', '.join(backends)})")
        for t in issue.get("targets") or []:
            if isinstance(t, str) and t != "*" and t not in targets:
                errs.append(f"{where}: unknown target {t!r} ({', '.join(targets)})")
        if issue.get("expect") not in EXPECT:
            errs.append(f"{where}: expect must be one of {EXPECT}, got {issue.get('expect')!r}")
        for tag in issue.get("tags") or []:
            if tag not in vocab:
                errs.append(f"{where}: tag {tag!r} is not declared under top-level tags:")
        fixed = issue.get("fixed-in")
        if fixed is not None and not re.fullmatch(r"\S+ \S+", str(fixed)):
            errs.append(f"{where}: fixed-in must be '<tool> <version>', got {fixed!r}")
    return errs


def applies(issue: dict, bslug: str, target: str) -> bool:
    return (any(t in ("*", target) for t in issue["targets"])
            and any(fnmatchcase(bslug, p) for p in issue["backends"]))


def is_coarse(issue: dict) -> bool:
    """Matches the whole cell rather than named tests: the crude mode."""
    return "*" in issue["tests"]


def cells_of(issue: dict, m: dict) -> list[str]:
    backends, targets = matrix_axes(m)
    return [f"{b}-{t}" for b in backends for t in targets if applies(issue, b, t)]


